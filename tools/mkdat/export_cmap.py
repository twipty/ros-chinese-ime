#!/usr/bin/env python3
"""Export Droid Sans Fallback's Unicode cmap into mkdat's checked-in codepoint list.

This is a *development-time* tool: run it when the bundled font changes, then
commit the generated data file. Normal builds only read the checked-in list,
so fontTools is not a build dependency.

    python3 tools/mkdat/export_cmap.py \
        --font m0/probe/reactos/Fonts/DroidSansFallback.ttf \
        --out tools/mkdat/data/droid_cmap.txt

The output is deterministic: sorted ascending, one 4-to-6 digit uppercase hex
codepoint per line, with a provenance header. mkdat parses it and marks a
character tier=1 when its codepoint is absent from this set.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

from fontTools.ttLib import TTFont


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--font", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args()

    font = TTFont(args.font, lazy=True)
    codepoints: set[int] = set()
    for table in font["cmap"].tables:
        if table.isUnicode():
            codepoints.update(table.cmap.keys())
    if not codepoints:
        raise SystemExit(f"{args.font}: no Unicode cmap subtables found")

    lines = [
        "# Unicode cmap of the ReactOS bundled Droid Sans Fallback font.",
        "# Generated by tools/mkdat/export_cmap.py -- do not edit by hand.",
        f"# source: {args.font.as_posix()}",
        f"# source-sha256: {sha256_of(args.font)}",
        f"# codepoints: {len(codepoints)}",
        "# Each line: one codepoint, uppercase hex, ascending.",
    ]
    lines.extend(f"{cp:04X}" for cp in sorted(codepoints))

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"wrote {args.out}: {len(codepoints)} codepoints")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
